"use client";
import { MultiLine, SimpleBar } from "@/components/Charts";
import { Badge, Table } from "@/components/ui";
import { Row } from "@/lib/api";

export function ResultView({ r }: { r: Row }) {
  const cols = (r.columns ?? []).map((c: Row) => c.name as string);
  const data = (r.rows ?? []).map((row: unknown[]) => Object.fromEntries(cols.map((c: string, i: number) => [c, row[i]])));
  const ch = r.chart;
  return (
    <>
      <p>
        <Badge kind={r.status}>{r.status.replace("_", " ")}</Badge>{" "}
        {r.mode === "demo_reference_sql" ? <Badge kind="demo" /> : r.mode === "claude" ? <Badge kind="model">Generated by {r.model}</Badge> : null}
      </p>
      {r.message && <div className={r.status === "answered" ? "" : "banner"} role={r.status === "answered" ? undefined : "alert"}>{r.message}</div>}
      {r.explanation && <p>{r.explanation}</p>}
      {r.sql && <><h2>SQL (validated, read-only, row-limited)</h2><pre aria-label="Generated SQL">{r.sql}</pre></>}
      {data.length > 0 && ch && ch.type === "bar" && <SimpleBar data={data} x={ch.x} y={ch.y} label={`Bar chart of ${ch.y} by ${ch.x}`} />}
      {data.length > 0 && ch && ch.type === "line" && <MultiLine data={data} x={ch.x} ys={[ch.y]} label={`Line chart of ${ch.y} over ${ch.x}`} />}
      {data.length > 0 && <Table rows={data} cols={cols.map((c: string) => ({ key: c, label: c }))} />}
      {r.status === "answered" && data.length === 0 && <div className="state">The query returned no rows.</div>}
      {r.masked_columns?.length > 0 && <p className="sub">Identifier columns are pseudonymised: {r.masked_columns.join(", ")}.</p>}
      {r.suppressed_rows > 0 && <p className="sub">{r.suppressed_rows} small-group row(s) suppressed to limit disclosure risk.</p>}
      {r.attempt_errors?.length > 0 && <details><summary>{r.attempts} attempt(s); {r.attempt_errors.length} rejected</summary><ul className="plain">{r.attempt_errors.map((e: Row, i: number) => <li key={i}>{e.stage}/{e.code}: {e.message}</li>)}</ul></details>}
      {r.model && <p className="sub">Tokens in/out: {r.input_tokens}/{r.output_tokens} · LLM {Math.round(r.llm_ms)} ms · DB {Math.round(r.db_ms)} ms</p>}
    </>
  );
}

