import time
from collections import defaultdict, deque

from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel, Field

from ..agents.text_to_sql.agent import BIAgent, BIResponse, demo_queries
from ..agents.text_to_sql.executor import ExecConfig
from ..agents.text_to_sql.llm import make_client
from ..agents.text_to_sql.semantic import load_examples
from ..config import get_settings
from .auth import analyst


class AskRequest(BaseModel):
    question: str = Field(min_length=1, max_length=2000)


class _Limiter:
    """In-memory per-client limiter (single process). Deployments should also enforce limits at the gateway."""

    def __init__(self, n: int, per_s: float):
        self.n, self.per = n, per_s
        self.hits: defaultdict[str, deque[float]] = defaultdict(deque)

    def check(self, key: str) -> None:
        now, q = time.monotonic(), self.hits[key]
        while q and now - q[0] > self.per:
            q.popleft()
        if len(q) >= self.n:
            raise HTTPException(429, "rate limit exceeded")
        q.append(now)


def build_router(log_dsn: str) -> APIRouter:
    s = get_settings()
    agent = BIAgent(s.bi_database_url, make_client(s.anthropic_api_key, s.bi_model),
                    ExecConfig(row_limit=s.bi_row_limit, mask_key=s.pii_mask_key), log_dsn)
    limiter = _Limiter(30, 60.0)

    def limit(request: Request):
        limiter.check(request.client.host if request.client else "anon")

    r = APIRouter(prefix="/bi", tags=["text-to-sql"], dependencies=[analyst, Depends(limit)])

    @r.get("/status")
    def status():
        return {"llm_available": agent.llm is not None, "model": agent.llm.model if agent.llm else None,
                "row_limit": s.bi_row_limit,
                "message": None if agent.llm else "Live LLM access unavailable: set ANTHROPIC_API_KEY. Demo queries still work."}

    @r.post("/query", response_model=BIResponse)
    def query(req: AskRequest):
        return agent.ask(req.question)

    @r.get("/demo")
    def demo():
        return {"label": "deterministic reference SQL, not generated by an LLM", "queries": demo_queries()}

    @r.post("/demo/{demo_id}", response_model=BIResponse)
    def run_demo(demo_id: str):
        e = next((x for x in load_examples() if x["id"] == demo_id), None)
        if not e:
            raise HTTPException(404, "unknown demo query")
        return agent.run_reference(e["sql"], e["question"], e.get("chart"))

    return r
