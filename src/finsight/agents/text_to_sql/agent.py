logger = logging.getLogger("finsight.bi")
Status = Literal["answered", "needs_clarification", "unanswerable", "rejected", "llm_unavailable", "error", "invalid_question"]


class BIResponse(BaseModel):
    status: Status
    mode: Literal["claude", "demo_reference_sql", "none"] = "none"
    message: str | None = None
    sql: str | None = None
    explanation: str | None = None
    columns: list[dict] = Field(default_factory=list)
    rows: list[list] = Field(default_factory=list)
    row_count: int = 0
    truncated: bool = False
    masked_columns: list[str] = Field(default_factory=list)
    suppressed_rows: int = 0
    chart: dict | None = None
    attempts: int = 0
    attempt_errors: list[dict] = Field(default_factory=list)
    model: str | None = None
    input_tokens: int = 0
    output_tokens: int = 0
    llm_ms: float = 0.0
    db_ms: float = 0.0
    retrieved_tables: list[str] = Field(default_factory=list)
    retrieved_terms: list[str] = Field(default_factory=list)


_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")
MAX_ATTEMPTS = 3


def check_question(q: str) -> str | None:
    q = (q or "").strip()
    if len(q) < 3:
        return "Please ask a complete question."
    if len(q) > 500:
        return "Question too long (max 500 characters)."
    if _CTRL.search(q):
        return "Question contains invalid characters."
    return None


class BIAgent:
    def __init__(self, bi_dsn: str, llm: LLMClient | None, exec_cfg: ExecConfig | None = None, log_dsn: str | None = None):
        self.bi_dsn, self.llm, self.cfg, self.log_dsn = bi_dsn, llm, exec_cfg or ExecConfig(), log_dsn

    # -- shared execution path (used by Claude answers and by labelled demo/reference queries) --------
    def _run_sql(self, sql: str, resp: BIResponse) -> tuple[bool, dict]:
        try:
            v = validate_sql(sql, self.cfg.row_limit)
        except PolicyViolation as e:
            return False, {"stage": "policy", "code": e.code, "message": e.message}
        try:
            r = execute(self.bi_dsn, v, self.cfg)
        except ExecutionError as e:
            return False, {"stage": "database", "code": e.code, "message": e.message}
        resp.sql, resp.columns, resp.rows = v.sql, r.columns, r.rows
        resp.row_count, resp.truncated, resp.masked_columns = len(r.rows), r.truncated, r.masked_columns
        resp.suppressed_rows, resp.db_ms = r.suppressed_rows, r.db_ms
        return True, {}

    def run_reference(self, sql: str, question: str, chart: dict | None = None) -> BIResponse:
        """Deterministic demo/eval path: runs approved SQL through the SAME policy + executor. Labelled, never 'claude'."""
        resp = BIResponse(status="answered", mode="demo_reference_sql", attempts=1)
        ok, err = self._run_sql(sql, resp)
        if not ok:
            resp.status, resp.message, resp.attempt_errors = "rejected" if err["stage"] == "policy" else "error", err["message"], [err]
            return self._finish(question, resp)
        resp.chart = build_chart(chart, resp.columns, resp.rows)
        resp.explanation = "Approved reference SQL (not generated by an LLM)."
        return self._finish(question, resp)

    def ask(self, question: str) -> BIResponse:
        with span("bi.ask", question_id=question_fingerprint(question or ""), **{"llm.provider": "anthropic"}) as sp:
            resp = self._ask(question)
            codes = [e.get("code") for e in resp.attempt_errors]
            sp.set_attribute("bi.status", resp.status)
            sp.set_attribute("bi.mode", resp.mode)
            sp.set_attribute("bi.attempts", resp.attempts)
            sp.set_attribute("bi.retries", max(resp.attempts - 1, 0))
            sp.set_attribute("bi.validation_failures", len([c for c in codes if c]))
            sp.set_attribute("bi.rows", resp.row_count)
            sp.set_attribute("bi.db_ms", resp.db_ms)
            sp.set_attribute("bi.llm_ms", resp.llm_ms)
            if resp.model:
                sp.set_attribute("llm.model", resp.model)
                sp.set_attribute("llm.input_tokens", resp.input_tokens)
                sp.set_attribute("llm.output_tokens", resp.output_tokens)
                sp.set_attribute("llm.estimated_usd", estimate_cost(resp.model, resp.input_tokens, resp.output_tokens)["estimated_usd"])
            return resp

    def _ask(self, question: str) -> BIResponse:
        bad = check_question(question)
        if bad:
            return BIResponse(status="invalid_question", message=bad)
        if self.llm is None:
            resp = BIResponse(status="llm_unavailable", message=(
                "Live LLM access is not configured. Set ANTHROPIC_API_KEY (see README) or use the labelled demo queries."))
            return self._finish(question, resp)
        ctx = retrieve(question)
        resp = BIResponse(status="error", mode="claude", model=self.llm.model,
                          retrieved_tables=ctx["tables"], retrieved_terms=ctx["terms"])
        context = render_context(ctx)
        prior: str | None = None
        for attempt in range(1, MAX_ATTEMPTS + 1):
            resp.attempts = attempt
            user = f"<context>\n{context}\n</context>\n<question>\n{question.strip()}\n</question>"
            if prior:
                user += f"\n<previous_attempt>\n{prior}\n</previous_attempt>\nFix the problem and resubmit."
            t0 = time.perf_counter()
            try:
                out = self.llm.generate(SYSTEM, user)
            except LLMUnavailable as e:
                resp.status, resp.message = "llm_unavailable", str(e)
                return self._finish(question, resp)
            resp.llm_ms += (time.perf_counter() - t0) * 1000
            resp.input_tokens += out.input_tokens
            resp.output_tokens += out.output_tokens
            ti = out.tool_input
            st = ti.get("status")
            if st == "clarify":
                resp.status, resp.message = "needs_clarification", str(ti.get("clarification_question") or "Please clarify the question.")
                return self._finish(question, resp)
            if st == "unanswerable":
                resp.status, resp.message = "unanswerable", str(ti.get("reason") or "The available data cannot answer this.")
                return self._finish(question, resp)
            sql = ti.get("sql") if st == "sql" else None
            if not isinstance(sql, str) or not sql.strip():   # wrong-shaped model output is a failed attempt, never executed
                prior = "No SQL was returned; call submit_query with status=sql, clarify or unanswerable."
                resp.attempt_errors.append({"stage": "format", "code": "no_sql", "message": "model returned no SQL"})
                continue
            ok, err = self._run_sql(sql, resp)
            if ok:
                expl, chart = ti.get("explanation"), ti.get("chart")
                resp.status, resp.explanation = "answered", expl if isinstance(expl, str) else None
                resp.chart = build_chart(chart if isinstance(chart, dict) else None, resp.columns, resp.rows)
                return self._finish(question, resp)
            resp.attempt_errors.append(err)
            prior = f"SQL: {sql[:1500]}\nError ({err['stage']}/{err['code']}): {err['message']}"
        last = resp.attempt_errors[-1] if resp.attempt_errors else {"stage": "?", "message": "unknown"}
        resp.status = "rejected" if last["stage"] == "policy" else "error"
        resp.message = f"Could not produce a valid query after {MAX_ATTEMPTS} attempts: {last['message']}"
        resp.sql = None
        return self._finish(question, resp)

    def _finish(self, question: str, resp: BIResponse) -> BIResponse:
        BI_QUERIES.labels(resp.status, resp.mode).inc()
        if resp.model:
            BI_TOKENS.labels("input").inc(resp.input_tokens)
            BI_TOKENS.labels("output").inc(resp.output_tokens)
            BI_LLM_SECONDS.observe(resp.llm_ms / 1000)
        log(logger, logging.INFO, "bi_query", status=resp.status, mode=resp.mode, attempts=resp.attempts, rows=resp.row_count)
        if self.log_dsn:
            try:
                with psycopg.connect(self.log_dsn, autocommit=True, connect_timeout=3) as c:
                    last_err = resp.attempt_errors[-1]["code"] if resp.attempt_errors else None
                    c.execute(
                        "INSERT INTO core.bi_query_log (question_sha256, question_preview, mode, status, sql, attempts, row_count, "
                        "error_category, model, input_tokens, output_tokens, llm_ms, db_ms) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                        (hashlib.sha256(question.encode()).hexdigest(), question.strip()[:200], resp.mode, resp.status, resp.sql,
                         resp.attempts, resp.row_count, last_err or (resp.status if resp.status not in ("answered",) else None),
                         resp.model, resp.input_tokens, resp.output_tokens, resp.llm_ms, resp.db_ms))
            except psycopg.Error:
                log(logger, logging.WARNING, "bi_log_write_failed")
        return resp


def demo_queries() -> list[dict]:
    return [{"id": e["id"], "question": e["question"]} for e in load_examples()]
